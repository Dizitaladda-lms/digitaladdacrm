import dotenv from "dotenv";
dotenv.config();

import pkg from "pg";
import logger from "../utils/logger.js";
const { Pool } = pkg;

const rawConnectionString = process.env.DATABASE_URL || "";
const normalizedConnectionString = rawConnectionString
  .replace(/^DATABASE_URL\s*=\s*/, "")
  .trim()
  .replace(/^['"]|['"]$/g, "");

if (!normalizedConnectionString) {
  throw new Error("❌ DATABASE_URL is missing in environment variables.");
}

const pool = new Pool({
  connectionString: normalizedConnectionString,
  ssl: process.env.DB_SSL === "true"
    ? { rejectUnauthorized: false }
    : undefined,
  max: 10,
  idleTimeoutMillis: 30000,
  connectionTimeoutMillis: 10000,
});

pool.on("error", (error) => {
  logger.error("PostgreSQL pool client error; connection will be replaced.", {
    error: error.message,
    stack: error.stack,
  });
});

pool
  .connect()
  .then(async (client) => {
    console.log("✅ PostgreSQL (Neon) Connected Successfully");
    try {
      await client.query(`
        ALTER TABLE leads DROP CONSTRAINT IF EXISTS leads_status_check;
        ALTER TABLE leads ADD CONSTRAINT leads_status_check CHECK (
          UPPER(status) IN (
            'NEW', 'INTERESTED', 'FOLLOW_UP', 'VISITED', 'ENROLLED', 'NOT_INTERESTED',
            'CONTACTED', 'QUALIFIED', 'ADMISSION_DONE', 'LOST', 'PENDING', 'COMPLETED', 'REJECTED'
          )
        );

        ALTER TABLE leads ADD COLUMN IF NOT EXISTS first_source VARCHAR(50);
        ALTER TABLE leads ADD COLUMN IF NOT EXISTS previous_source VARCHAR(50);
        ALTER TABLE leads ADD COLUMN IF NOT EXISTS source_history JSONB;

        ALTER TABLE employees ADD COLUMN IF NOT EXISTS domain VARCHAR(150);
        ALTER TABLE employees ADD COLUMN IF NOT EXISTS assigned_domains JSONB DEFAULT '[]'::jsonb;

        CREATE TABLE IF NOT EXISTS admissions (
          id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          admission_code      VARCHAR(40) NOT NULL UNIQUE,
          lead_id             BIGINT REFERENCES leads(id) ON DELETE SET NULL,
          student_name        VARCHAR(150) NOT NULL,
          mobile              VARCHAR(20) NOT NULL,
          email               VARCHAR(255),
          course_name         VARCHAR(200) NOT NULL,
          campus_centre       VARCHAR(200),
          total_fee           NUMERIC(14, 2) NOT NULL DEFAULT 0,
          paid_fee            NUMERIC(14, 2) NOT NULL DEFAULT 0,
          pending_fee         NUMERIC(14, 2) NOT NULL DEFAULT 0,
          receipt_no          VARCHAR(100),
          payment_mode        VARCHAR(50) DEFAULT 'CASH',
          next_due_date       DATE,
          status              VARCHAR(30) NOT NULL DEFAULT 'ENROLLED',
          assigned_to         BIGINT REFERENCES employees(id) ON DELETE SET NULL,
          remarks             TEXT,
          created_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
          updated_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
        );
      `);
      console.log("✅ Database Lead Status Constraint & Admissions Schema Synced Successfully");
    } catch (syncErr) {
      console.warn("⚠️ Lead Status & Admissions Schema Sync Notice:", syncErr.message);
    } finally {
      client.release();
    }
  })
  .catch((err) => {
    console.error("❌ PostgreSQL Connection Error:", err.message);
    if (process.env.VERCEL !== "1") {
      process.exit(1);
    }
  });

export async function query(text, params) {
  return pool.query(text, params);
}

export async function withTransaction(callback) {
  const client = await pool.connect();

  try {
    await client.query("BEGIN");

    const result = await callback(client);

    await client.query("COMMIT");

    return result;
  } catch (err) {
    await client.query("ROLLBACK");
    throw err;
  } finally {
    client.release();
  }
}

export default pool;
