BEGIN;

CREATE TABLE IF NOT EXISTS employee_wfh_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  employee_id BIGINT NOT NULL REFERENCES employees(id) ON DELETE CASCADE,
  department_id BIGINT REFERENCES departments(id) ON DELETE SET NULL,
  start_date DATE NOT NULL,
  end_date DATE NOT NULL,
  reason TEXT NOT NULL,
  status VARCHAR(40) NOT NULL DEFAULT 'PENDING_HR' CHECK (
    status IN ('PENDING_HR', 'APPROVED', 'REJECTED')
  ),
  hr_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  hr_reviewed_at TIMESTAMPTZ,
  rejection_reason TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CHECK (end_date >= start_date)
);

CREATE INDEX IF NOT EXISTS idx_employee_wfh_requests_user_created
  ON employee_wfh_requests (user_id, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_employee_wfh_requests_status
  ON employee_wfh_requests (status);

CREATE INDEX IF NOT EXISTS idx_employee_wfh_requests_dates
  ON employee_wfh_requests (employee_id, start_date, end_date);

COMMIT;
