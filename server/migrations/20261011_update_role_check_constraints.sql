-- Migration: Update users & employees role check constraints
-- Supports all CRM & 6-Level Hierarchy roles:
-- SUPER_ADMIN, ADMIN, MANAGER, SALES_HEAD, DEPARTMENT_HEAD,
-- HR, TL, SUB_TL, COUNSELLOR, EMPLOYEE, TRAINER, INTERN
-- =====================================================

BEGIN;

ALTER TABLE IF EXISTS users DROP CONSTRAINT IF EXISTS users_role_check;
ALTER TABLE IF EXISTS users
  ADD CONSTRAINT users_role_check CHECK (
    UPPER(role) IN (
      'ADMIN', 'SUPER_ADMIN', 'MANAGER', 'SALES_HEAD', 'DEPARTMENT_HEAD',
      'HR', 'TL', 'SUB_TL', 'COUNSELLOR', 'EMPLOYEE', 'TRAINER', 'INTERN'
    )
  );

ALTER TABLE IF EXISTS employees DROP CONSTRAINT IF EXISTS employees_role_check;
ALTER TABLE IF EXISTS employees
  ADD CONSTRAINT employees_role_check CHECK (
    UPPER(role) IN (
      'ADMIN', 'SUPER_ADMIN', 'MANAGER', 'SALES_HEAD', 'DEPARTMENT_HEAD',
      'HR', 'TL', 'SUB_TL', 'COUNSELLOR', 'EMPLOYEE', 'TRAINER', 'INTERN'
    )
  );

ALTER TABLE IF EXISTS users ADD COLUMN IF NOT EXISTS reports_to BIGINT REFERENCES users(id) ON DELETE SET NULL;
ALTER TABLE IF EXISTS users ADD COLUMN IF NOT EXISTS department_id BIGINT REFERENCES departments(id) ON DELETE SET NULL;

ALTER TABLE IF EXISTS daily_work_reports DROP CONSTRAINT IF EXISTS chk_report_status;
ALTER TABLE IF EXISTS daily_work_reports
  ADD COLUMN IF NOT EXISTS interns_work_summary TEXT,
  ADD COLUMN IF NOT EXISTS report_type VARCHAR(20) NOT NULL DEFAULT 'DAILY',
  ADD COLUMN IF NOT EXISTS current_status VARCHAR(40) NOT NULL DEFAULT 'PENDING',
  ADD COLUMN IF NOT EXISTS current_level_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS current_approval_level INTEGER;

CREATE TABLE IF NOT EXISTS report_approvals (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_id         BIGINT NOT NULL REFERENCES daily_work_reports(id) ON DELETE CASCADE,
  approver_id       BIGINT REFERENCES users(id) ON DELETE SET NULL,
  acted_by_id       BIGINT REFERENCES users(id) ON DELETE SET NULL,
  level             INTEGER NOT NULL,
  role_label        VARCHAR(50) NOT NULL,
  status            VARCHAR(30) NOT NULL DEFAULT 'PENDING',
  remarks           TEXT,
  is_auto_approved  BOOLEAN NOT NULL DEFAULT FALSE,
  acted_at          TIMESTAMPTZ,
  created_at        TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at        TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (report_id, level)
);

CREATE INDEX IF NOT EXISTS idx_report_approvals_report_level ON report_approvals(report_id, level ASC);
CREATE INDEX IF NOT EXISTS idx_report_approvals_approver_status ON report_approvals(approver_id, status);

COMMIT;
