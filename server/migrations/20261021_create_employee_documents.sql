BEGIN;

CREATE TABLE IF NOT EXISTS employee_documents (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id BIGINT NOT NULL REFERENCES employees(id) ON DELETE CASCADE,
  uploaded_by_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  document_type VARCHAR(30) NOT NULL CHECK (document_type IN ('AADHAAR_CARD', 'PAN_CARD', 'OFFICE_DOCUMENT', 'OTHER', 'PROFILE_PHOTO')),
  document_label VARCHAR(120) NOT NULL,
  original_filename VARCHAR(255) NOT NULL,
  mime_type VARCHAR(100) NOT NULL,
  size_bytes INTEGER NOT NULL CHECK (size_bytes > 0 AND size_bytes <= 5242880),
  cloudinary_public_id TEXT NOT NULL UNIQUE,
  cloudinary_resource_type VARCHAR(20) NOT NULL DEFAULT 'raw',
  cloudinary_version VARCHAR(40),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_employee_documents_employee_created
  ON employee_documents(employee_id, created_at DESC);

COMMIT;
